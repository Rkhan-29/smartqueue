import type { ApiError, AuthResponse } from '../types/api';

export const API_URL: string = (import.meta.env.VITE_API_URL ?? '').replace(/\/+$/, '');

const ACCESS_KEY = 'sq.access';
const REFRESH_KEY = 'sq.refresh';
export const SESSION_KEY = 'sq.session';

function read(key: string): string | null {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}
function write(key: string, value: string | null) {
  try {
    if (value === null) localStorage.removeItem(key);
    else localStorage.setItem(key, value);
  } catch {
    /* storage unavailable (private mode): the session just won't persist */
  }
}

export const tokenStore = {
  access: () => read(ACCESS_KEY),
  refresh: () => read(REFRESH_KEY),
  set(auth: Pick<AuthResponse, 'accessToken' | 'refreshToken'>) {
    write(ACCESS_KEY, auth.accessToken);
    write(REFRESH_KEY, auth.refreshToken);
  },
  clear() {
    write(ACCESS_KEY, null);
    write(REFRESH_KEY, null);
  },
};

/** Guest identity: lets a guest rejoin/see only their own active token. Opaque, generated by the server. */
export const guestSession = {
  get: () => read(SESSION_KEY),
  set: (id: string) => write(SESSION_KEY, id),
};

/** Error thrown for every non-2xx response, carrying the backend's stable error code. */
export class HttpError extends Error {
  status: number;
  code: string;
  fieldErrors?: Record<string, string>;
  constructor(status: number, body: Partial<ApiError> | null) {
    super(body?.message || 'Something went wrong. Please try again.');
    this.status = status;
    this.code = body?.code || (status === 0 ? 'NETWORK_ERROR' : 'UNKNOWN');
    this.fieldErrors = body?.fieldErrors;
  }
}

type Json = Record<string, unknown> | unknown[] | undefined;
interface Options {
  method?: string;
  body?: Json;
  auth?: boolean;
  headers?: Record<string, string>;
  signal?: AbortSignal;
}

let refreshing: Promise<boolean> | null = null;
let onSessionExpired: (() => void) | null = null;
export const setSessionExpiredHandler = (fn: (() => void) | null) => {
  onSessionExpired = fn;
};

async function tryRefresh(): Promise<boolean> {
  const refreshToken = tokenStore.refresh();
  if (!refreshToken) return false;
  // One refresh at a time: the backend rotates refresh tokens, so parallel refreshes would invalidate each other.
  // Concurrent callers share the in-flight promise; it is cleared as soon as it settles so a later 401
  // always triggers a fresh attempt.
  if (refreshing) return refreshing;
  const attempt = (async () => {
    try {
      const res = await fetch(`${API_URL}/api/auth/refresh`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ refreshToken }),
      });
      if (!res.ok) return false;
      tokenStore.set((await res.json()) as AuthResponse);
      return true;
    } catch {
      return false;
    }
  })();
  refreshing = attempt;
  try {
    return await attempt;
  } finally {
    if (refreshing === attempt) refreshing = null;
  }
}

async function send(path: string, opts: Options, token: string | null): Promise<Response> {
  const headers: Record<string, string> = { Accept: 'application/json', ...opts.headers };
  if (opts.body !== undefined) headers['Content-Type'] = 'application/json';
  if (token) headers.Authorization = `Bearer ${token}`;
  try {
    return await fetch(`${API_URL}${path}`, {
      method: opts.method ?? 'GET',
      headers,
      body: opts.body === undefined ? undefined : JSON.stringify(opts.body),
      signal: opts.signal,
    });
  } catch (e) {
    if (e instanceof DOMException && e.name === 'AbortError') throw e;
    throw new HttpError(0, { message: 'Cannot reach the server. Check your connection and try again.' });
  }
}

export async function request<T>(path: string, opts: Options = {}): Promise<T> {
  const wantsAuth = opts.auth !== false;
  let res = await send(path, opts, wantsAuth ? tokenStore.access() : null);

  if (res.status === 401 && wantsAuth && tokenStore.refresh()) {
    if (await tryRefresh()) {
      res = await send(path, opts, tokenStore.access());
    } else {
      tokenStore.clear();
      onSessionExpired?.();
    }
  }

  if (!res.ok) {
    let body: Partial<ApiError> | null = null;
    try {
      body = (await res.json()) as ApiError;
    } catch {
      /* non-JSON error body */
    }
    throw new HttpError(res.status, body);
  }
  if (res.status === 204) return undefined as T;
  return (await res.json()) as T;
}

export const get = <T>(path: string, opts?: Options) => request<T>(path, opts);
export const post = <T>(path: string, body?: Json, opts?: Options) =>
  request<T>(path, { ...opts, method: 'POST', body });
export const put = <T>(path: string, body?: Json, opts?: Options) =>
  request<T>(path, { ...opts, method: 'PUT', body });
